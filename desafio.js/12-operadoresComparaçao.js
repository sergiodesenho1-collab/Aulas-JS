// Operadores Lógicos de comparção
// Em javaScript,os operadores de comparação são usados para
// comparar dois valores e retornar um valor booleano (true ou false)
// com base na comparação . Aqui estão os principais operadores de comparção:

// 1. Igualdade (==): Verifica se os valores são iguais, ignorando o tipo de dados.
// 2. Estritamente Igual (===): Verifica se os valores são iguais e do mesmo tipo.
// 3. Desigualdade ( !=):Verifica se os valores são diferente ,ignodando o tipo de dado.
// 4.Estritamente desigaul (!==): Verifica se os valores são diferentes ou de tipo de dados diferentes.
// 5.Maior que (>): Verifica se o valor e da esquerda é maior que o valor  da dreita.
// 6. Menor que (<); Verifica se o valor da esquerda ~e menor que oo valor da direira .
// 7.Maior ou igual (>=):Verifica se o valor da esquerda é maior ou igual o da direita.

// Igualdade (==)
console.log("Igual (==");
console.log(5 == "5"); // true, porque realiza coreção de tipo
console.log(5 == 5); // true
console.log(5 == 10); //false

// Estritamente Igual (===)
console.log("Estritamente Igual (===");
console.log(5 === "5");
console.log(5 === 5);
console.log(5 === 10);

//Desigualdade (!=)
console.log("Desigualdade (!=");
console.log(5 != "5");
console.log(5 != 5);
console.log(5 != 10);

//Etritamente Desigual (!==)
console.log("Desigualdade (!==");
console.log(5 !== "5");
console.log(5 !== 5);
console.log(5 !== 10);

// Maior que (>)
console.log("Maior que (>)");
console.log(10 > 5);
console.log(5 > 10);
console.log(5 > 5);

//Menor que (<)
console.log("Menor que (<)");
console.log(10 < 5);
console.log(5 < 10);
console.log(5 < 5);

//Maiorou Igual que (>=)
console.log("Maior ou igual que (>=");
console.log(10 >= 5);
console.log(5 >= 10);
console.log(5 >= 5);

//Menor ou Igual que (<=)
console.log("Menor ou igual que (<=");
console.log(10 <= 5);
console.log(5 <= 10);
console.log(5 <= 5);
